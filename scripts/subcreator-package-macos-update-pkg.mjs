// // Build one universal macOS update PKG containing only the extension and bundled fonts.
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");
const stagingRoot = path.join(projectRoot, ".subcreator-macos-update-staging");
const scriptsDir = path.join(stagingRoot, "scripts");
const packagesDir = path.join(stagingRoot, "packages");
const releasesDir = path.join(projectRoot, "Releases");
const npmCommand = "npm";

function runCommand(command, args, options = {}) {
  // // Execute native build and packaging commands with visible output and strict exit handling.
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: options.cwd || projectRoot,
      env: {
        ...process.env,
        ...(options.env || {})
      },
      stdio: options.stdio || "inherit"
    });

    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`${command} exited with code ${code}`));
    });
  });
}

async function pathExists(targetPath) {
  // // Probe optional payload paths without failing on a normal missing-file result.
  try {
    await stat(targetPath);
    return true;
  } catch {
    return false;
  }
}

async function readPackageVersion() {
  // // Use package.json as the single source for the update package version and filename.
  const raw = await readFile(path.join(projectRoot, "package.json"), "utf8");
  return String(JSON.parse(raw).version || "").trim();
}

async function prunePackagingMetadata(targetDir) {
  // // Remove Finder and AppleDouble files so the update contains only intentional assets.
  const entries = await readdir(targetDir, { withFileTypes: true });
  for (const entry of entries) {
    const entryPath = path.join(targetDir, entry.name);
    if (entry.name === ".DS_Store" || entry.name.startsWith("._")) {
      await rm(entryPath, { recursive: entry.isDirectory(), force: true });
      continue;
    }
    if (entry.isDirectory()) {
      await prunePackagingMetadata(entryPath);
    }
  }
}

async function stageUpdatePayload() {
  // // Stage only the extension, fonts, and lightweight postinstall script.
  await rm(stagingRoot, { recursive: true, force: true });
  await mkdir(path.join(scriptsDir, "payload", "dist"), { recursive: true });
  await mkdir(packagesDir, { recursive: true });

  const extensionSource = path.join(projectRoot, "dist", "com.cyrilplugin.subcreator");
  if (!(await pathExists(extensionSource))) {
    throw new Error(`Built extension is missing: ${extensionSource}`);
  }
  await cp(
    extensionSource,
    path.join(scriptsDir, "payload", "dist", "com.cyrilplugin.subcreator"),
    { recursive: true }
  );

  const fontsSource = path.join(projectRoot, "Fonts");
  if (await pathExists(fontsSource)) {
    await cp(fontsSource, path.join(scriptsDir, "payload", "Fonts"), { recursive: true });
  }

  await cp(
    path.join(projectRoot, "installers", "subcreator_update_macos.sh"),
    path.join(scriptsDir, "postinstall")
  );
  await runCommand("chmod", ["755", path.join(scriptsDir, "postinstall")]);
  await prunePackagingMetadata(scriptsDir);
  await runCommand("xattr", ["-cr", scriptsDir]);
}

async function buildUpdatePackage(version) {
  // // Build a script-only component package and wrap it in a universal macOS Installer product.
  const componentPath = path.join(packagesDir, "SubCreatorUpdate.pkg");
  await runCommand("pkgbuild", [
    "--nopayload",
    "--scripts",
    scriptsDir,
    "--identifier",
    "com.cyrilplugin.subcreator.installer.update",
    "--version",
    version,
    componentPath
  ], {
    env: {
      COPYFILE_DISABLE: "1"
    }
  });

  const distributionPath = path.join(stagingRoot, "Distribution.xml");
  const distribution = `<?xml version="1.0" encoding="utf-8"?>
<!-- // Generated by subcreator-package-macos-update-pkg.mjs. -->
<installer-gui-script minSpecVersion="2">
  <title>Update Sub Creator</title>
  <organization>com.cyrilplugin.subcreator</organization>
  <domains enable_localSystem="true"/>
  <options customize="never" require-scripts="false" hostArchitectures="arm64,x86_64"/>
  <choices-outline>
    <line choice="update"/>
  </choices-outline>
  <choice id="update" visible="false" start_selected="true">
    <pkg-ref id="com.cyrilplugin.subcreator.installer.update"/>
  </choice>
  <pkg-ref id="com.cyrilplugin.subcreator.installer.update" version="${version}" onConclusion="none">SubCreatorUpdate.pkg</pkg-ref>
</installer-gui-script>
`;
  await writeFile(distributionPath, distribution, "utf8");

  const outputPath = path.join(releasesDir, `SubCreator-v${version}-macOS-Update.pkg`);
  const signingIdentity = process.env.SUBCREATOR_MAC_INSTALLER_IDENTITY || "";
  const productArgs = [
    "--distribution",
    distributionPath,
    "--package-path",
    packagesDir
  ];

  await mkdir(releasesDir, { recursive: true });
  await rm(outputPath, { force: true });
  if (signingIdentity) {
    productArgs.push("--sign", signingIdentity, outputPath);
  } else {
    productArgs.push(outputPath);
  }
  await runCommand("productbuild", productArgs, {
    env: {
      COPYFILE_DISABLE: "1"
    }
  });

  const notaryProfile = process.env.SUBCREATOR_NOTARY_PROFILE || "";
  if (notaryProfile) {
    // // Submit and staple the final update package when release notarization credentials are configured.
    await runCommand("xcrun", [
      "notarytool",
      "submit",
      outputPath,
      "--keychain-profile",
      notaryProfile,
      "--wait"
    ]);
    await runCommand("xcrun", ["stapler", "staple", outputPath]);
  }

  if (signingIdentity) {
    // // Verify the requested Developer ID signature before reporting a successful package build.
    await runCommand("pkgutil", ["--check-signature", outputPath]);
  } else {
    // // Expand unsigned development packages to verify that the product archive is readable.
    const validationDir = path.join(stagingRoot, "package-validation");
    await runCommand("pkgutil", ["--expand", outputPath, validationDir]);
    await rm(validationDir, { recursive: true, force: true });
  }

  process.stdout.write(`Universal macOS update package created at ${outputPath}\n`);
}

async function main() {
  // // Build the extension and package its architecture-independent update payload on macOS.
  if (process.platform !== "darwin") {
    throw new Error("macOS update PKG packaging must run on macOS.");
  }

  const version = await readPackageVersion();
  if (!version) {
    throw new Error("package.json does not contain a version.");
  }

  if (process.env.SUBCREATOR_SKIP_EXTENSION_BUILD !== "1") {
    await runCommand(npmCommand, ["run", "subcreator:build"]);
  }
  await stageUpdatePayload();
  await buildUpdatePackage(version);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.stack || error.message : String(error)}\n`);
  process.exit(1);
});
